/**
 * Dashboard Share Service
 *
 * Generates and shares a clean financial summary image.
 * Uses local file storage (no server upload).
 */

import { Share } from 'react-native';
import * as Sharing from 'expo-sharing';

export interface ShareSummaryData {
  month: string;
  openingBalance: number;
  contributionsReceived: number;
  waterExpenses: number;
  closingBalance: number;
  paidMembers: number;
  totalMembers: number;
  totalCanes: number;
  totalHeld: number;
}

/**
 * Share dashboard summary as image via native share sheet
 *
 * Generates a clean image and opens the native Android share sheet.
 * User can select WhatsApp, Messages, Email, etc.
 *
 * Note: Requires the actual image to be generated by caller using ViewShot.
 * This handles the file and sharing portion.
 */
export async function shareDashboardSummary(
  imageUri: string,
  month: string
): Promise<void> {
  try {
    // Format month for share message
    const [year, monthNum] = month.split('-');
    const date = new Date(parseInt(year), parseInt(monthNum) - 1);
    const monthLabel = date.toLocaleDateString('en-US', { year: 'numeric', month: 'long' });

    // Share via native sheet directly with image URI from ViewShot
    const isAvailable = await Sharing.isAvailableAsync();

    if (isAvailable) {
      await Sharing.shareAsync(imageUri, {
        mimeType: 'image/jpeg',
        dialogTitle: `Water Bill - ${monthLabel}`,
      });
    } else {
      // Fallback to React Native Share if native sharing unavailable
      await Share.share({
        url: imageUri,
        title: `Water Bill - ${monthLabel}`,
        message: `Water Fund bill for ${monthLabel}`,
      });
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : 'Failed to share bill';
    throw new Error(`Share failed: ${message}`);
  }
}


/**
 * Format month string to readable format
 */
export function formatMonthForShare(month: string): string {
  const [year, monthNum] = month.split('-');
  const date = new Date(parseInt(year), parseInt(monthNum) - 1);
  return date.toLocaleDateString('en-US', { year: 'numeric', month: 'long' });
}
